export const ESPECES_PAR_ID: Record<string, EspeceDef> = Object.fromEntries(
  ESPECES.map((e) => [e.id, e]),
);

export function getEspece(id: string): EspeceDef {
  const e = ESPECES_PAR_ID[id];
  if (!e) throw new Error(`Espèce inconnue : ${id}`);
  return e;
}
